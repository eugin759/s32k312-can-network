/**
 * @file can_app_config.h
 * @brief Centralized compile-time configuration for multi-node CAN architecture,
 *        hardware abstraction, filtering modes, and node identification.
 */

#ifndef CAN_APP_CONFIG_H
#define CAN_APP_CONFIG_H

/* =========================================================================
 * 1. PANEL DE CONTROL DEL NODO (Modificar unicamente esta seccion por placa)
 * ========================================================================= */
#define NODE_ID             3       /**< Node role: 1, 2, 3, or 4 */

/* Seleccion de hardware fisico (Descomentar SOLO UNO en S32K312) */
#define CAN_HW_EXTERNAL             /**< External TJA1051 (5V USB-powered board) */
// #define CAN_HW_INTERNAL          /**< Onboard TJA1043/1463 (12V healthy board) */

/* Modos de operacion y prueba */
#define CAN_DEBUG_MODE              /**< Comment out for strict 0x7FF hardware filtering */
// #define ARBITRATION_TEST         /**< Uncomment for 10 ms periodic burst arbitration test */
// #define INVALID_ID_TEST          /**< Uncomment to transmit TEST_INVALID_ID (0x555) */

/* Set to 0 to use the 500 kbps timing generated by RTD; 1 retains the runtime fallback. */
#define CAN_USE_RUNTIME_BITTIMING_PATCH 1U
#if (CAN_USE_RUNTIME_BITTIMING_PATCH != 0U) && (CAN_USE_RUNTIME_BITTIMING_PATCH != 1U)
    #error "CAN_USE_RUNTIME_BITTIMING_PATCH must be 0 or 1"
#endif

/* =========================================================================
 * 2. VALIDACION DE CONFIGURACION DE HARDWARE
 * ========================================================================= */
#if defined(CAN_HW_EXTERNAL) && defined(CAN_HW_INTERNAL)
    #error "Select ONLY ONE hardware transceiver mode: CAN_HW_EXTERNAL or CAN_HW_INTERNAL"
#endif
#if !defined(CAN_HW_EXTERNAL) && !defined(CAN_HW_INTERNAL)
    #error "Select one hardware transceiver mode: CAN_HW_EXTERNAL or CAN_HW_INTERNAL"
#endif

#if defined(CAN_HW_INTERNAL)
    #define CAN_FLEXCAN_INSTANCE 0U
#else
    #define CAN_FLEXCAN_INSTANCE 1U
#endif

/* =========================================================================
 * 3. IDENTIDAD LOGICA, IDs CAN Y SUSCRIPCIONES POR NODO
 * ========================================================================= */
#if (NODE_ID == 1)
    #define NODE_NAME       "MASTER"
    #define NODE_TX_ID      0x100U
    #define NODE_RX_ID_1    0x200U
    #define NODE_RX_ID_2    0x300U
#elif (NODE_ID == 2)
    #define NODE_NAME       "DASHBOARD"
    #define NODE_TX_ID      0x200U
    #define NODE_RX_ID_1    0x100U
    #define NODE_RX_ID_2    0x400U
#elif (NODE_ID == 3)
    #define NODE_NAME       "POWERTRAIN"
    #define NODE_TX_ID      0x300U
    #define NODE_RX_ID_1    0x100U
    #define NODE_RX_ID_2    0x200U
#elif (NODE_ID == 4)
    #define NODE_NAME       "BODY_CTRL"
    #define NODE_TX_ID      0x400U
    #define NODE_RX_ID_1    0x200U
    #define NODE_RX_ID_2    0x300U
#else
    #error "Invalid NODE_ID defined in can_app_config.h (must be 1..4)"
#endif

/** @brief Unsubscribed ID used to prove hardware filtering rejects unwanted traffic without CPU IRQ */
#define TEST_INVALID_ID     0x555U

/* =========================================================================
 * 4. MASCARA DE FILTRADO HARDWARE Y PERIODOS
 * ========================================================================= */
#ifdef CAN_DEBUG_MODE
    #define CAN_RX_FILTER_MASK  0x000U  /**< Accept all standard 11-bit frames */
#else
    #define CAN_RX_FILTER_MASK  0x7FFU  /**< Strict 11-bit exact ID match */
#endif

#define ARBITRATION_PERIOD_MS   10U     /**< Transmission period during arbitration test */
#define TELEMETRY_PERIOD_MS     1000U   /**< Diagnostic UART print interval */
#define CAN_CLASSIC_DATA_LENGTH 8U

#if defined(ARBITRATION_TEST)
    #define CAN_TX_PERIOD_MS    ARBITRATION_PERIOD_MS
#else
    #define CAN_TX_PERIOD_MS    TELEMETRY_PERIOD_MS
#endif

#if defined(ARBITRATION_TEST) && defined(INVALID_ID_TEST)
    #error "ARBITRATION_TEST and INVALID_ID_TEST must be tested separately"
#endif

#endif /* CAN_APP_CONFIG_H */
